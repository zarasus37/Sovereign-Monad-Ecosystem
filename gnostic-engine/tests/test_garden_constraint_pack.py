"""Tests for the Council garden → constraint pack PoC.

Validates the pack generated by `scripts/garden-to-constraint-pack.mjs`:
- loads via the existing `load_constraint_pack` loader,
- has the expected rule count + at least one well-known rule,
- carries soft severity (not charter-grade),
- the three_domain_reading field is preserved in each rule's params.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from gnostic_engine.constraints.loader import (
    ConstraintRule,
    DomainPack,
    load_constraint_pack,
)


GARDEN_PACK_VERSION = "0.1.0-gardens"
EXPECTED_RULE_COUNT = 9  # Aristotle garden — events 01-09
KNOWN_RULE_ID = "ARISTOTLE-EVENT-01"  # "All men by nature desire to know"


def test_garden_pack_loads() -> None:
    """The garden pack must load via the existing loader without modification."""
    pack = load_constraint_pack(GARDEN_PACK_VERSION)
    assert isinstance(pack.version, str)
    assert pack.version == GARDEN_PACK_VERSION
    # The garden pack only has one domain file (theological) in the PoC;
    # the other two slots still exist on the ConstraintPack object but are
    # empty (no rules). Check that AT LEAST one domain has the rules.
    domain_packs = [pack.theological, pack.technological, pack.cosmological]
    populated = [d for d in domain_packs if d.rules]
    assert len(populated) >= 1, "Expected at least one non-empty domain pack"


def test_garden_pack_rule_count() -> None:
    """The Aristotle pack has 9 events; the populated domain should have all 9."""
    pack = load_constraint_pack(GARDEN_PACK_VERSION)
    populated = [d for d in (pack.theological, pack.technological, pack.cosmological) if d.rules]
    total = sum(len(d.rules) for d in populated)
    assert total == EXPECTED_RULE_COUNT, (
        f"Expected {EXPECTED_RULE_COUNT} rules across the pack, got {total}"
    )


def test_garden_pack_known_rule_exists() -> None:
    """ARISTOTLE-EVENT-01 must be present with the expected title and shape."""
    pack = load_constraint_pack(GARDEN_PACK_VERSION)
    all_rules = [r for d in (pack.theological, pack.technological, pack.cosmological) for r in d.rules]
    matching = [r for r in all_rules if r.id == KNOWN_RULE_ID]
    assert matching, f"Rule {KNOWN_RULE_ID} not found in pack"
    rule = matching[0]
    assert isinstance(rule, ConstraintRule)
    assert rule.name == "All men by nature desire to know"
    assert rule.severity == "soft"
    assert "desire to know" in rule.description


def test_garden_pack_rule_has_three_domain_reading() -> None:
    """Each rule must carry the source figure's Three-Domain Reading in params."""
    pack = load_constraint_pack(GARDEN_PACK_VERSION)
    for d in (pack.theological, pack.technological, pack.cosmological):
        for rule in d.rules:
            assert "three_domain_reading" in rule.params, (
                f"Rule {rule.id} missing three_domain_reading"
            )
            tdr = rule.params["three_domain_reading"]
            for domain in ("theology", "technology", "cosmology"):
                assert domain in tdr, f"Rule {rule.id} missing {domain} in three_domain_reading"


def test_garden_pack_severity_is_soft() -> None:
    """Garden rules are advisory (severity=soft), not charter-grade (hard)."""
    pack = load_constraint_pack(GARDEN_PACK_VERSION)
    for d in (pack.theological, pack.technological, pack.cosmological):
        for rule in d.rules:
            assert rule.severity == "soft", (
                f"Rule {rule.id} has severity={rule.severity}; garden rules must be soft"
            )


def test_garden_pack_manifest_references_generator() -> None:
    """The manifest must point back to the source garden and the generator."""
    pack = load_constraint_pack(GARDEN_PACK_VERSION)
    assert "derivation" in pack.manifest
    assert "garden-to-constraint-pack.mjs" in pack.manifest.get("derivation", "")
    assert pack.manifest.get("name", "").startswith("council-gardens/")


def test_garden_pack_charter_pack_still_loads() -> None:
    """The charter pack (v1.1.0) must continue to load unchanged alongside the garden pack."""
    charter_pack = load_constraint_pack("1.1.0")
    assert charter_pack.version == "1.1.0"
    # The charter pack has hard rules; the garden pack has only soft.
    charter_rules = [
        r for d in (charter_pack.theological, charter_pack.technological, charter_pack.cosmological) for r in d.rules
    ]
    assert any(r.severity == "hard" for r in charter_rules)


if __name__ == "__main__":
    import sys

    sys.exit(pytest.main([__file__, "-v"]))
